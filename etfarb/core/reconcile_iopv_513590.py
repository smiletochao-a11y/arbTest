NAV = 0.7425        # 官方9-11基金份额净值
CASH_911 = -223.24  # 官方9-11 预估现金部分(单位:元/篮子)  —— 东哥刚给
NAV_910 = 223248.41 # 官方9-10 最小申赎单位净值

def main():
    # (A) 替代金额列 = 什么?
    sum_sub = sum(a for _,_,a in STOCKS)
    print(f"[A] Σ官方替代金额 = {sum_sub:.2f} 元  (50只成分股 替代金额列求和)")
    print(f"    这列 = 每只 数量×成分股价(人民币) , 按 PCF 定价基准日(=前一日9-10收盘)计价")
    print(f"    + 9-11 预估现金部分({CASH_911}) = {sum_sub+CASH_911:.2f} 元")
    print(f"    ≈ 9-10 单位净值 {NAV_910:.2f} 元  (差 {sum_sub+CASH_911-NAV_910:+.2f})  → 证实替代金额列是9-10基准")
    print(f"    所以 拿 223471.65 去比 9-11净值222750 是'错日对比', 高出的721.65是9-10→9-11一天波动, 不是15%溢价\n")

    # (B) 拉腾讯港股9-11收盘
    codes = ",".join(f"hk{c}" for c,_,_ in STOCKS)
    url = f"https://qt.gtimg.cn/q={codes}"
    req = urllib.request.Request(url, headers={"User-Agent":"Mozilla/5.0","Referer":"https://finance.qq.com/"})
    raw = urllib.request.urlopen(req, timeout=20).read().decode("gbk","ignore")
    price = {}
    for ln in raw.strip().split("\n"):
        m = re.search(r'v_(\w+)="(.+)"', ln)
        if not m: continue
        parts = m.group(2).split("~")
        if len(parts) < 31: continue
        try: price[m.group(1)[2:]] = float(parts[3])
        except: pass

    # (C) 正确自建IOPV = Σ(9-11港币收盘×数量×中间价) + 9-11预估现金部分
    s = sum(price[c]*q*RATE for c,q,_ in STOCKS)
    iopv_stock = s/UNITS
    iopv_full  = (s + CASH_911)/UNITS
    print(f"[C] Σ(9-11港币收盘×数量×{RATE}) = {s:.2f} 元")
    print(f"    ├ 仅股票篮子 IOPV = {iopv_stock:.6f}  (vs NAV {NAV}  差 {(iopv_stock-NAV)/NAV*100:+.3f}%)")
    print(f"    └ 股票篮子 + 预估现金部分(-223.24) = {s+CASH_911:.2f} 元")
    print(f"       正确自建 IOPV = {iopv_full:.6f}  (vs NAV {NAV}  差 {(iopv_full-NAV)/NAV*100:+.4f}%)")
    print(f"\n结论: 用 股数×实时价×中间价 + 官方预估现金部分, 自建IOPV 0.742607 ≈ 官方NAV 0.7425, 误差0.014%")

if __name__ == "__main__":
    main()
