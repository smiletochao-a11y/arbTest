def get_hk_closes(codes):
    """拉每只港股 9-10/9-11 收盘(腾讯港股历史K线), 返回 {code: {date: close}}"""
    import time
    out = {}
    for i,c in enumerate(codes):
        url=f"https://web.ifzq.gtimg.cn/appstock/app/hkfqkline/get?param=hk{c},day,2026-09-01,2026-09-14,15,qfq"
        req=urllib.request.Request(url, headers={"User-Agent":"Mozilla/5.0","Referer":"https://finance.qq.com/"})
        try:
            raw=urllib.request.urlopen(req,timeout=15,context=CTX).read().decode("gbk","ignore")
            d=json.loads(raw)["data"][f"hk{c}"]
            kl=d.get("qfqday") or d.get("day")
            dd={}
            for x in kl:
                dd[x[0][:10]]=float(x[2])   # [date, open, close, ...]
            out[c]=dd
        except Exception as e:
            out[c]={}
            print(f"  [warn] hk{c} 拉取失败: {e}")
        if (i+1) % 10 == 0:
            time.sleep(1.0)   # 限流保护
    return out

DATE = {"0910":"2026-09-10", "0911":"2026-09-11"}
def verify(day, pcf, closes):
    rate = RATE[day]
    off  = OFFICIAL[day]
    dkey = DATE[day]
    codes=[c for c,_,_ in pcf]
    # 取当日收盘
    price={}
    miss=[]
    for c,q,a in pcf:
        cl=closes.get(c,{})
        if dkey in cl: price[c]=cl[dkey]
        else: miss.append(c)
    if miss:
        print(f"  [warn] {day} 缺失收盘价: {miss}")
    # (1) 自建实物篮子 (HKD收盘 × 数量 × 中间价)
    basket = sum(price[c]*q*rate for c,q,a in pcf if c in price)
    off_sub = sum(a for c,q,a in pcf)
    # (2) 核对 替代金额列 = 收盘价×数量×汇率 ?
    my_sub = sum(price[c]*q*rate for c,q,a in pcf if c in price)
    diff_sub = my_sub - off_sub
    # (3) 单位净值 = (篮子 + 现金差额)/份额
    nav_via_diff = (basket + off["cash_diff"]) / UNITS
    # (4) 预估IOPV (仅9-11有预估现金部分)
    est_cash = off.get("est_cash")
    if est_cash is not None:
        iopv_est = (basket + est_cash) / UNITS
    else:
        iopv_est = None
    print(f"\n========== {day} 验证 ==========")
    print(f"  中间价 HKD→CNY        = {rate}")
    print(f"  成分股数              = {len(pcf)}  (取到收盘 {len(price)} 只)")
    print(f"  自建实物篮子 Σ        = {basket:,.2f} 元")
    print(f"  官方替代金额列 Σ      = {off_sub:,.2f} 元   (差 {diff_sub:+,.2f}, {diff_sub/off_sub*100:+.3f}%)")
    print(f"  ── 用现金差额核对单位净值 ──")
    print(f"  篮子 + 现金差额({off['cash_diff']:+.2f}) = {basket+off['cash_diff']:,.2f}")
    print(f"  自建单位净值          = {nav_via_diff:.6f}  (÷{UNITS})")
    print(f"  官方单位净值          = {off['nav_per']:.6f}   (差 {(nav_via_diff-off['nav_per'])/off['nav_per']*100:+.4f}%)")
    print(f"  官方单位净值×份额     = {off['unit_nav']:,.2f}   (差 {basket+off['cash_diff']-off['unit_nav']:+,.2f})")
    if iopv_est is not None:
        print(f"  ── 用预估现金部分核对盘中IOPV ──")
        print(f"  篮子 + 预估现金部分({est_cash:+.2f}) = {basket+est_cash:,.2f}")
        print(f"  预估IOPV(盘中)       = {iopv_est:.6f}")
        print(f"  官方NAV(盘后)        = {off['nav_per']:.6f}   (差 {(iopv_est-off['nav_per'])/off['nav_per']*100:+.4f}%)")
        print(f"  ※ 预估vs实际差额 = {est_cash - off['cash_diff']:+,.2f} 元 (={ (est_cash-off['cash_diff'])/off['unit_nav']*100:+.3f}% , 即IOPV预估误差来源)")
    return basket

